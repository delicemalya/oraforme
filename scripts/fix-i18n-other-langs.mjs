// Language block boundaries (re-read from file after FR was updated)
const langs = ['en', 'pt', 'es', 'ln', 'sw', 'de', 'kg']
const langBlockStarts = {
  en: '  en: {',
  pt: '  pt: {',
  es: '  es: {',
  ln: '  ln: {',
  sw: '  sw: {',
  de: '  de: {',
  kg: '  kg: {',
}
const nextLang = { en: 'pt', pt: 'es', es: 'ln', ln: 'sw', sw: 'de', de: 'kg', kg: null }

let content = fs.readFileSync(i18nPath, 'utf8')

for (const lang of langs) {
  const newKeys = NEW_KEYS[lang]
  if (!newKeys) continue

  // Find this language's block boundaries
  const blockStartStr = `\n${langBlockStarts[lang]}`
  const blockStartPos = content.indexOf(blockStartStr)
  if (blockStartPos === -1) {
    console.log(`  ${lang}: Cannot find block, skipping`)
    continue
  }

  const nl = nextLang[lang]
  const blockEndPos = nl
    ? content.indexOf(`\n${langBlockStarts[nl]}`, blockStartPos + 1)
    : content.length

  const block = content.substring(blockStartPos, blockEndPos)

  // Filter keys that don't exist in THIS block
  const keysToAdd = Object.entries(newKeys).filter(([key]) => {
    return !block.includes(`'${key}':`)
  })

  if (keysToAdd.length === 0) {
    console.log(`  ${lang}: No new keys to add`)
    continue
  }

  // Find last 'common.' key in this block
  const commonMatches = [...block.matchAll(/    'common\.[^']+':.*,/g)]
  if (commonMatches.length === 0) {
    console.log(`  ${lang}: No common anchor found, inserting at start of block`)
    continue
  }

  const lastCommon = commonMatches[commonMatches.length - 1]
  const insertAt = blockStartPos + lastCommon.index + lastCommon[0].length

  const keysStr = keysToAdd.map(([key, val]) =>
    `    '${key}':${' '.repeat(Math.max(1, 24 - key.length))}'${String(val).replace(/'/g, "\\'")}',`
  ).join('\n')

  const before = content.substring(0, insertAt)
  const after = content.substring(insertAt)
  content = before + '\n' + keysStr + after

  console.log(`  ${lang}: Added ${keysToAdd.length} new keys`)
}

fs.writeFileSync(i18nPath, content, 'utf8')
console.log('Done! All language blocks updated.')
