// ─── Fonction de traduction (avec fallback fr) ────────────────────────────────

export function t(key: string, locale: Locale = 'fr'): string {
  return translations[locale]?.[key] ?? translations['fr'][key] ?? key
}

// ─── Stockage localStorage ────────────────────────────────────────────────────

export function getStoredLocale(): Locale {
  if (typeof window === 'undefined') return 'fr'
  const stored = localStorage.getItem('oraforme_locale') as Locale
  return SUPPORTED_LOCALES.includes(stored) ? stored : 'fr'
}

export function setStoredLocale(locale: Locale): void {
  if (typeof window === 'undefined') return
  localStorage.setItem('oraforme_locale', locale)
}

